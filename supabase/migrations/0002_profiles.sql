-- 0002_profiles.sql
-- Application-level profile, one row per authenticated user.
-- public.profiles.id IS the Supabase Auth UUID — no parallel identity system.
-- Passwords and auth data are never stored here (auth.users owns that).

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '',
  avatar_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

-- Auto-create a profile when a new auth user signs up. security definer so
-- it can write profiles regardless of the caller's own RLS on profiles; it
-- reads only auth.users fields and inserts exactly one matching profile.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'display_name', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
